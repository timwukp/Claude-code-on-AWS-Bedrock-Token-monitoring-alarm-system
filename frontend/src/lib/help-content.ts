export type HelpId = keyof typeof HELP;

const BY_LABEL: Map<string, HelpId> = new Map();
for (const [id, entry] of Object.entries(HELP) as [HelpId, HelpEntry][]) {
  for (const l of entry.labels ?? []) BY_LABEL.set(l, id);
}

/** Exact-label lookup so existing cards gain an info button without being edited. */
export function helpIdForLabel(label: string): HelpId | undefined {
  return BY_LABEL.get(label);
}
