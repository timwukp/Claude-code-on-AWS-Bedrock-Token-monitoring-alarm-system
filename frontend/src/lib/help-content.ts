/**
 * The single registry behind every ⓘ button. One entry answers, in order: what is this, why does it
 * matter, how is it calculated, what are the caveats, where to read more. Content here was lifted
 * from the captions and caveat paragraphs that used to sit on the card faces, so nothing that was
 * disclosed is lost — it is relocated behind one accessible control.
 */

