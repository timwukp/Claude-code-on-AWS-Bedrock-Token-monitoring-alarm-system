/**
 * Lakehouse spec compiler. `spec/lakehouse/*.schema.json` is the single source of truth for every
 * table; this turns it into the artefacts the code consumes:
 *   spec/lakehouse/generated/tables.json           — what the CDK stack reads to declare S3 Tables / Glue columns
 *   backend/lambdas/lakehouse/generated/row-types.ts — TypeScript row interfaces for the transform Lambda
 * `generated.test.ts` regenerates in memory and compares byte-for-byte, so a spec edit that is not
 * followed by `npx ts-node scripts/gen-lakehouse-ddl.ts` fails CI instead of drifting.
 */
import * as fs from 'fs';
import * as path from 'path';

export type IcebergType = 'string' | 'long' | 'double' | 'boolean' | 'timestamp';

export interface LakehouseColumn { name: string; icebergType: IcebergType; required: boolean; description: string }

export interface LakehouseTable {
  layer: string;
  table: string;
  storage: 's3tables' | 'glue-external';
  partition: string[];
  retention: string;
  pii: boolean;
  firehoseRoute?: { stream: string; match: string };
  description: string;
  columns: LakehouseColumn[];
}

interface JsonSchemaProp { type?: string; format?: string; description?: string }
interface SpecDoc {
  title: string;
  description?: string;
  properties: Record<string, JsonSchemaProp>;
  required?: string[];
  'x-lakehouse': { layer: string; table: string; storage: 's3tables' | 'glue-external'; partition: string[]; retention: string; pii: boolean; firehoseRoute?: { stream: string; match: string } };
}

export function icebergTypeOf(prop: JsonSchemaProp, column: string): IcebergType {
  if (prop.type === 'string' && prop.format === 'date-time') return 'timestamp';
  if (prop.type === 'string') return 'string';
  if (prop.type === 'integer') return 'long';
  if (prop.type === 'number') return 'double';
  if (prop.type === 'boolean') return 'boolean';
  throw new Error(`unsupported JSON Schema type for column ${column}: ${JSON.stringify(prop)}`);
}

export function buildTables(specDir: string): LakehouseTable[] {
  const files = fs.readdirSync(specDir).filter((f) => f.endsWith('.schema.json')).sort();
  return files.map((f) => {
    const doc = JSON.parse(fs.readFileSync(path.join(specDir, f), 'utf8')) as SpecDoc;
    const meta = doc['x-lakehouse'];
    if (!meta) throw new Error(`${f}: missing x-lakehouse`);
    if (`${meta.layer}.${meta.table}.schema.json` !== f) throw new Error(`${f}: file name must be <layer>.<table>.schema.json`);
    const required = new Set(doc.required ?? []);
    const columns: LakehouseColumn[] = Object.entries(doc.properties).map(([name, prop]) => {
      if (!/^[a-z][a-z0-9_]*$/.test(name)) throw new Error(`${f}: column ${name} is not snake_case`);
      return { name, icebergType: icebergTypeOf(prop, name), required: required.has(name), description: prop.description ?? '' };
    });
    for (const r of required) if (!doc.properties[r]) throw new Error(`${f}: required column ${r} is not a property`);
    for (const p of meta.partition) {
      const col = p.replace(/^[a-z]+\((.*)\)$/, '$1');
      if (!doc.properties[col]) throw new Error(`${f}: partition ${p} names an unknown column`);
    }
    return {
      layer: meta.layer, table: meta.table, storage: meta.storage, partition: meta.partition, retention: meta.retention,
      pii: meta.pii, ...(meta.firehoseRoute ? { firehoseRoute: meta.firehoseRoute } : {}), description: doc.description ?? '', columns,
    };
  });
}

const TS_TYPE: Record<IcebergType, string> = { string: 'string', long: 'number', double: 'number', boolean: 'boolean', timestamp: 'string' };

export function pascal(s: string): string {
  return s.split(/[_.]/).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

export function renderRowTypes(tables: LakehouseTable[]): string {
  const out: string[] = [
    '// GENERATED by backend/scripts/gen-lakehouse-ddl.ts from spec/lakehouse/*.schema.json — do not edit.',
    '// timestamp columns are ISO-8601 strings on the wire; long/double are numbers.',
    '',
  ];
  for (const t of tables) {
    out.push(`/** ${t.layer}.${t.table} — ${t.description} */`);
    out.push(`export interface ${pascal(t.layer)}${pascal(t.table)}Row {`);
    for (const c of t.columns) out.push(`  ${c.name}${c.required ? '' : '?'}: ${TS_TYPE[c.icebergType]}${c.required ? '' : ' | null'};`);
    out.push('}', '');
  }
  out.push('export const LAKEHOUSE_TABLES = {');
  for (const t of tables) out.push(`  ${pascal(t.layer).toUpperCase()}_${t.table.toUpperCase()}: { layer: '${t.layer}', table: '${t.table}' },`);
  out.push('} as const;', '');
  return out.join('\n');
}

export function renderTablesJson(tables: LakehouseTable[]): string {
  return JSON.stringify({ generatedBy: 'backend/scripts/gen-lakehouse-ddl.ts', tables }, null, 2) + '\n';
}

export const REPO_ROOT = path.resolve(__dirname, '..', '..');
export const SPEC_DIR = path.join(REPO_ROOT, 'spec', 'lakehouse');
export const TABLES_JSON = path.join(SPEC_DIR, 'generated', 'tables.json');
export const ROW_TYPES_TS = path.join(REPO_ROOT, 'backend', 'lambdas', 'lakehouse', 'generated', 'row-types.ts');

if (require.main === module) {
  const tables = buildTables(SPEC_DIR);
  fs.mkdirSync(path.dirname(TABLES_JSON), { recursive: true });
  fs.mkdirSync(path.dirname(ROW_TYPES_TS), { recursive: true });
  fs.writeFileSync(TABLES_JSON, renderTablesJson(tables));
  fs.writeFileSync(ROW_TYPES_TS, renderRowTypes(tables));
  console.log(`wrote ${tables.length} tables → ${path.relative(REPO_ROOT, TABLES_JSON)}, ${path.relative(REPO_ROOT, ROW_TYPES_TS)}`);
}
